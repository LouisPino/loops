#!/usr/bin/env node
/* Regenerates library.js from every sequence file in this folder.
   Run it after adding, renaming, or removing a .json sequence:

       node sync.js

   The dropdown reads library.js, which also inlines each sequence so the
   page works when index.html is opened straight off the disk, where the
   browser refuses to fetch neighbouring files. */

const fs = require('fs');
const path = require('path');

const dir = __dirname;
const looksLikeSequence = d =>
  Array.isArray(d) || (d && typeof d === 'object' && Array.isArray(d.measures || d.sequence || d.bars));

const inline = {};
const skipped = [];

for (const name of fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort()) {
  let data;
  try {
    data = JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));
  } catch (err) {
    skipped.push(`${name} — not valid JSON (${err.message})`);
    continue;
  }
  if (!looksLikeSequence(data)) {
    skipped.push(`${name} — no measures array`);
    continue;
  }
  inline[name] = data;
}

const files = Object.keys(inline);

fs.writeFileSync(path.join(dir, 'library.js'),
`/* Generated by "node sync.js" — edit the .json files, not this one. */
window.LOOPS_LIBRARY = ${JSON.stringify({ files, inline }, null, 2)};
`);

console.log(`library.js — ${files.length} sequence${files.length === 1 ? '' : 's'}: ${files.join(', ') || 'none'}`);
skipped.forEach(s => console.log(`  skipped ${s}`));
